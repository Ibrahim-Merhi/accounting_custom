import frappe


def arabic_amount_in_words(amount, currency):

    # ========================================================
    # BASIC NUMBERS - MASCULINE
    # ========================================================

    masculine_ones = {
        0: "",
        1: "واحد",
        2: "اثنان",
        3: "ثلاثة",
        4: "أربعة",
        5: "خمسة",
        6: "ستة",
        7: "سبعة",
        8: "ثمانية",
        9: "تسعة",
        10: "عشرة",
        11: "أحد عشر",
        12: "اثنا عشر",
        13: "ثلاثة عشر",
        14: "أربعة عشر",
        15: "خمسة عشر",
        16: "ستة عشر",
        17: "سبعة عشر",
        18: "ثمانية عشر",
        19: "تسعة عشر"
    }


    # ========================================================
    # BASIC NUMBERS - FEMININE
    # Used for ليرة
    # ========================================================

    feminine_ones = {
        0: "",
        1: "إحدى",
        2: "اثنتان",
        3: "ثلاث",
        4: "أربع",
        5: "خمس",
        6: "ست",
        7: "سبع",
        8: "ثماني",
        9: "تسع",
        10: "عشر",
        11: "إحدى عشرة",
        12: "اثنتا عشرة",
        13: "ثلاث عشرة",
        14: "أربع عشرة",
        15: "خمس عشرة",
        16: "ست عشرة",
        17: "سبع عشرة",
        18: "ثماني عشرة",
        19: "تسع عشرة"
    }


    tens = {
        20: "عشرون",
        30: "ثلاثون",
        40: "أربعون",
        50: "خمسون",
        60: "ستون",
        70: "سبعون",
        80: "ثمانون",
        90: "تسعون"
    }


    # Receipt/accounting wording:
    # 200 -> مائتي
    hundreds = {
        1: "مائة",
        2: "مائتي",
        3: "ثلاثمائة",
        4: "أربعمائة",
        5: "خمسمائة",
        6: "ستمائة",
        7: "سبعمائة",
        8: "ثمانمائة",
        9: "تسعمائة"
    }


    # ========================================================
    # NUMBER BELOW 100
    # ========================================================

    def under_100(number, feminine=False):

        number = int(number)

        if number == 0:
            return ""

        if feminine:
            words = feminine_ones
        else:
            words = masculine_ones

        if number < 20:
            return words.get(number, "")

        unit = number % 10
        ten = (number // 10) * 10

        if unit == 0:
            return tens.get(ten, "")

        return (
            words.get(unit, "")
            + " و"
            + tens.get(ten, "")
        )


    # ========================================================
    # NUMBER BELOW 1000
    #
    # Examples:
    # 100 -> مائة
    # 200 -> مائتي
    # 225 -> مائتي وخمسة وعشرون
    # 500 -> خمسمائة
    # ========================================================

    def under_1000(number, feminine=False):

        number = int(number)

        if number == 0:
            return ""

        if number < 100:
            return under_100(
                number,
                feminine
            )

        hundred_part = number // 100
        remainder = number % 100

        result = hundreds.get(
            hundred_part,
            ""
        )

        if remainder:
            result = (
                result
                + " و"
                + under_100(
                    remainder,
                    feminine
                )
            )

        return result


    # ========================================================
    # SCALE WORDS
    #
    # ألف / مليون / مليار
    #
    # Examples:
    #
    # 1,000
    # ألف
    #
    # 2,000
    # ألفان
    #
    # 3,000
    # ثلاثة آلاف
    #
    # 25,000
    # خمسة وعشرون ألف
    #
    # 200,000
    # مائتي ألف
    #
    # 5,000,000
    # خمسة ملايين
    # ========================================================

    def scale_words(
        quantity,
        singular,
        dual,
        plural,
        compound_form
    ):

        quantity = int(quantity)

        if quantity == 0:
            return ""

        if quantity == 1:
            return singular

        if quantity == 2:
            return dual

        quantity_text = under_1000(
            quantity,
            False
        )

        last_two = quantity % 100


        # ----------------------------------------------------
        # 3 - 10
        #
        # ثلاثة آلاف
        # خمسة ملايين
        # ----------------------------------------------------

        if 3 <= quantity <= 10:
            return (
                quantity_text
                + " "
                + plural
            )


        # ----------------------------------------------------
        # Values ending in 3 - 10
        #
        # 103,000
        # مائة وثلاثة آلاف
        # ----------------------------------------------------

        if 3 <= last_two <= 10:
            return (
                quantity_text
                + " "
                + plural
            )


        # ----------------------------------------------------
        # Exact hundreds
        #
        # 100,000 -> مائة ألف
        # 200,000 -> مائتي ألف
        # 300,000 -> ثلاثمائة ألف
        # ----------------------------------------------------

        if quantity % 100 == 0:
            return (
                quantity_text
                + " "
                + singular
            )


        # ----------------------------------------------------
        # Other compound values
        #
        # 11,000
        # أحد عشر ألف
        #
        # 25,000
        # خمسة وعشرون ألف
        #
        # 775,000
        # سبعمائة وخمسة وسبعون ألف
        # ----------------------------------------------------

        return (
            quantity_text
            + " "
            + compound_form
        )


    # ========================================================
    # MAIN INTEGER CONVERTER
    # ========================================================

    def number_to_arabic(
        number,
        feminine_final=False
    ):

        number = int(number)

        if number == 0:
            return "صفر"

        if number < 0:
            return (
                "سالب "
                + number_to_arabic(
                    abs(number),
                    feminine_final
                )
            )

        parts = []


        # ----------------------------------------------------
        # BILLIONS
        # ----------------------------------------------------

        billions = (
            number // 1000000000
        )

        number = (
            number % 1000000000
        )

        if billions:
            parts.append(
                scale_words(
                    billions,
                    "مليار",
                    "ملياران",
                    "مليارات",
                    "مليار"
                )
            )


        # ----------------------------------------------------
        # MILLIONS
        # ----------------------------------------------------

        millions = (
            number // 1000000
        )

        number = (
            number % 1000000
        )

        if millions:
            parts.append(
                scale_words(
                    millions,
                    "مليون",
                    "مليونان",
                    "ملايين",
                    "مليون"
                )
            )


        # ----------------------------------------------------
        # THOUSANDS
        # ----------------------------------------------------

        thousands = (
            number // 1000
        )

        number = (
            number % 1000
        )

        if thousands:
            parts.append(
                scale_words(
                    thousands,
                    "ألف",
                    "ألفان",
                    "آلاف",
                    "ألف"
                )
            )


        # ----------------------------------------------------
        # FINAL 0 - 999
        # ----------------------------------------------------

        if number:
            parts.append(
                under_1000(
                    number,
                    feminine_final
                )
            )


        return " و".join(parts)


    # ========================================================
    # USD
    # ========================================================

    def format_usd(number):

        number = int(number)

        if number == 0:
            return "صفر دولار أمريكي"

        if number == 1:
            return "دولار أمريكي واحد"

        if number == 2:
            return "دولاران أمريكيان"


        words = number_to_arabic(
            number,
            False
        )

        last_two = number % 100


        # ----------------------------------------------------
        # 3 - 10
        #
        # ثلاثة دولارات أمريكية
        # ----------------------------------------------------

        if 3 <= number <= 10:
            return (
                words
                + " دولارات أمريكية"
            )


        # ----------------------------------------------------
        # Values ending in 3 - 10
        # ----------------------------------------------------

        if 3 <= last_two <= 10:
            return (
                words
                + " دولارات أمريكية"
            )


        # ----------------------------------------------------
        # 11 - 99
        #
        # خمسة وعشرون دولارًا أمريكيًا
        # ----------------------------------------------------

        if 11 <= last_two <= 99:
            return (
                words
                + " دولارًا أمريكيًا"
            )


        # ----------------------------------------------------
        # 100 / 200 / 500 / 1000 / etc.
        #
        # مائة دولار أمريكي
        # مائتي دولار أمريكي
        # خمسمائة دولار أمريكي
        # ----------------------------------------------------

        return (
            words
            + " دولار أمريكي"
        )


    # ========================================================
    # USD CENTS
    # ========================================================

    def format_cents(number):

        number = int(number)

        if number == 0:
            return ""

        if number == 1:
            return "سنت أمريكي واحد"

        if number == 2:
            return "سنتان أمريكيان"


        words = number_to_arabic(
            number,
            False
        )

        last_two = number % 100


        if 3 <= number <= 10:
            return (
                words
                + " سنتات أمريكية"
            )


        if 3 <= last_two <= 10:
            return (
                words
                + " سنتات أمريكية"
            )


        return (
            words
            + " سنتًا أمريكيًا"
        )


    # ========================================================
    # LBP
    # ========================================================

    def format_lbp(number):

        number = int(number)

        if number == 0:
            return "صفر ليرة لبنانية"

        if number == 1:
            return "ليرة لبنانية واحدة"

        if number == 2:
            return "ليرتان لبنانيتان"


        words = number_to_arabic(
            number,
            True
        )

        last_two = number % 100


        # ----------------------------------------------------
        # 3 - 10
        #
        # خمس ليرات لبنانية
        # ----------------------------------------------------

        if 3 <= number <= 10:
            return (
                words
                + " ليرات لبنانية"
            )


        # ----------------------------------------------------
        # Values ending in 3 - 10
        # ----------------------------------------------------

        if 3 <= last_two <= 10:
            return (
                words
                + " ليرات لبنانية"
            )


        # ----------------------------------------------------
        # Other values
        #
        # خمس وعشرون ليرة لبنانية
        # مائة ليرة لبنانية
        # مائتي ليرة لبنانية
        # ----------------------------------------------------

        return (
            words
            + " ليرة لبنانية"
        )


    # ========================================================
    # NORMALIZE VALUES
    # ========================================================

    amount = float(
        amount or 0
    )

    currency = (
        currency or ""
    ).strip().upper()


    if amount < 0:
        frappe.throw(
            "Donation Amount cannot be negative."
        )


    # ========================================================
    # USD
    # ========================================================

    if currency == "USD":

        rounded_amount = round(
            amount,
            2
        )


        whole_amount = int(
            rounded_amount
        )


        cents = int(
            round(
                (
                    rounded_amount
                    - whole_amount
                )
                * 100
            )
        )


        # ----------------------------------------------------
        # ROUNDING PROTECTION
        # ----------------------------------------------------

        if cents >= 100:

            whole_amount = (
                whole_amount + 1
            )

            cents = 0


        # ----------------------------------------------------
        # USD + CENTS
        #
        # 200.25
        # مائتي دولار أمريكي
        # وخمسة وعشرون سنتًا أمريكيًا
        # فقط لا غير
        # ----------------------------------------------------

        if (
            whole_amount > 0
            and cents > 0
        ):

            return (
                format_usd(
                    whole_amount
                )
                + " و"
                + format_cents(
                    cents
                )
                + " فقط لا غير"
            )


        # ----------------------------------------------------
        # CENTS ONLY
        # ----------------------------------------------------

        if (
            whole_amount == 0
            and cents > 0
        ):

            return (
                format_cents(
                    cents
                )
                + " فقط لا غير"
            )


        # ----------------------------------------------------
        # WHOLE USD
        # ----------------------------------------------------

        return (
            format_usd(
                whole_amount
            )
            + " فقط لا غير"
        )


    # ========================================================
    # LBP
    # ========================================================

    if currency == "LBP":

        whole_amount = int(
            round(amount)
        )

        return (
            format_lbp(
                whole_amount
            )
            + " فقط لا غير"
        )


    # ========================================================
    # OTHER CURRENCY
    # ========================================================

    whole_amount = int(
        round(amount)
    )

    return (
        number_to_arabic(
            whole_amount,
            False
        )
        + " "
        + currency
        + " فقط لا غير"
    )
